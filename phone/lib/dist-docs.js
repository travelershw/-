/**
 * 分发包里的两份纯文本文档。
 *
 * 放在 `lib/` 里而不是塞进 `tools/make-dist.js`:这两份文字是要给"拿到 APK 的另一个人"
 * 看的,属于交付内容,和版本号/地址一样值得单独维护与 review。
 *
 * @module qingyu-phone/lib/dist-docs
 */

/**
 * 《安装与使用说明.txt》。
 * @param {object} info 打包信息。
 * @param {string} info.version 版本号。
 * @param {string} info.apkFileName 包内 APK 文件名。
 * @param {string} info.apkSha256 APK 的 SHA-256。
 * @param {string} info.tailscaleUrl Tailscale 地址。
 * @param {string} info.lanPlaceholder 同一个 WiFi 的占位地址。
 * @returns {string} 纯文本(UTF-8)。
 */
export function installGuide(info) {
  return `轻语 · 手机端 v${info.version} 安装与使用说明
====================================================
(纯文本,手机和电脑都能直接打开看)

一、这是什么
  手机端的"轻语":点一下「开始对话」就能连着聊,声音会传到家里那台电脑上识别成文字,
  由"她"生成回答,再把她的声音传回手机播出来。也可以拍一张照片发给她看。
  用之前请确认家里那台电脑是开着的、中转程序在跑。

二、怎么装
  1. 把「${info.apkFileName}」传到手机(微信/QQ/USB 线/网盘都行);
  2. 在手机上点开这个 apk 文件;
  3. 系统会提示"不允许安装未知来源的应用",按提示允许即可。
     华为:设置 → 安全 → 更多安全设置 → 安装外部来源应用 → 允许(文件管理 / 浏览器);
     其它品牌一般在 设置 → 应用 → 特殊权限 里,搜"安装未知应用"。
  4. 装好后桌面会出现一个叫「轻语」的图标。

  签名说明:这一版和 v0.1.0 用的是同一个测试签名,已经装过旧版的手机可以直接覆盖安装
  升级(不用卸载,数据也保留)。这是自用的测试签名,不是应用商店的签名;传到别的手机
  安装时系统可能再问一次"是否允许安装未知来源应用"。

三、连上她(两条路,任选一条)
  A. 装了 Tailscale(推荐:人在外面、用流量也能连)
     1) 手机装 Tailscale,登录**和家里电脑同一个账号**;
     2) 打开轻语,点地址框下面的「家里(Tailscale)」按钮,会自动填:
        ${info.tailscaleUrl}
     3) 令牌留空即可(走 tailnet 身份认证);
     4) 点「连接」。状态显示"已握手 ready"就通了。

  B. 手机和电脑在同一个 WiFi(不用装 Tailscale,但只能在家里用)
     1) 电脑那侧要用 --host 0.0.0.0 启动中转,例如:
        python phone_bridge.py --host 0.0.0.0
        并在 Windows 防火墙弹窗里允许"专用网络"访问(没弹窗就手动放行 6201 端口);
     2) 在电脑上执行 ipconfig,找到"IPv4 地址"(形如 192.168.1.100);
     3) 在轻语里点「同一个 WiFi」按钮,它会预填一个示例地址:
        ${info.lanPlaceholder}
        里面的 IP 只是示例,必须换成 ipconfig 看到的那个才能连上。
        例如电脑的 IPv4 是 192.168.1.37,地址就填:
        ws://192.168.1.37:6201/
     4) **令牌这一条路必填**(留空一定连不上):中转只监听本机时才认"身份认证",
        一旦对外监听就只认令牌。令牌找作者要,别写在群里或公开的地方。
     5) 点「连接」。
     顺路提示:同一 WiFi 下,手机浏览器打开 http://<电脑IP>:6201/?token=<令牌>
     就是这个中转的自助页面,可以直接在页面上下载安装包、抄连接参数。

  地址和令牌只需要填一次,之后打开 App 会自动记住。

四、权限(第一次使用时系统会逐个问)
  · 麦克风:「开始对话」要用,**必须允许**;
  · 附近的设备 / 蓝牙:用来看耳机状态,**建议允许**;
  · 通知:连接期间挂常驻通知保活,**建议允许**(不允许也能用,只是切后台更容易被系统掐断)。

五、怎么用
  点「连接」→ 等状态变成"已握手 ready" → 点一下「**开始对话**」,然后**直接说话就行**:
  你停顿一下(约 0.8 秒),这一句会自动发出去;她说话的时候 App 自动闭麦,她说完自动接着听。
  想结束就再点一下「结束对话」。上方「她听到的」会显示识别出来的文字(用来确认收音对不对),
  她的回答会自动播出来。
  只想问一句、不想让它一直听着:用旁边的「**说一句**」——点一下开始录,再点一下结束并发送
  (最长 30 秒,按钮上会显示已经录了几秒)。
  也可以点「拍照」拍一张发给她,或者用下面的输入框直接发文字。

六、已知限制(不是 bug,先看这里)
  1. 部分手机(尤其是华为/鸿蒙)不把蓝牙耳机的麦克风开放给第三方 App。这时 App 会自动
     改用手机麦,耳机仍然用来放她的声音;页面上会写明原因。想知道本机到底给不给蓝牙
     麦克风,可以点「SCO 试验」看结果。
     想用"耳机上的麦":插一副**带麦的有线耳机(3.5mm)或 USB-C 耳麦**,App 会自动优先用它。
  2. 必须家里那台电脑开着、中转在跑,否则连不上(手机上会显示"连接出错")。
  3. 切后台/熄屏时 App 会挂一个常驻通知来保活;华为/鸿蒙还需要去
     设置 → 应用和服务 → 应用管理 → 轻语 → 耗电管理 → 打开「允许后台活动」。
  4. 还没做的:她主动开口说话;更省电的后台策略(现在靠前台服务)。

七、出问题怎么办
  在 App 里点「复制诊断」,把那一段文字直接发给作者。里面有设备型号、权限状态、蓝牙耳机
  状态、每次录音用的麦克风、连接记录,能直接定位问题,不用来回猜。

八、这个包的指纹(想核对文件有没有传坏可以看)
  APK: ${info.apkFileName}
  SHA-256: ${info.apkSha256}
  (Windows 上算:certutil -hashfile "${info.apkFileName}" SHA256)
`;
}

/**
 * 《版本说明.txt》。
 * @param {object} info 版本信息。
 * @param {string} info.version 版本号。
 * @param {number} info.versionCode versionCode。
 * @returns {string} 纯文本(UTF-8)。
 */
export function releaseNotes(info) {
  return `轻语 · 手机端 版本说明
====================================================

v${info.version}(本版,versionCode ${info.versionCode})
  · **对话模式(开关式)**:点一下「开始对话」就一直听着 —— 你说话停顿约 0.8 秒,
    这一句自动发出去;她说的时候 App **自动闭麦**(不会把她自己的声音录回来),
    她说完自动接着听;再点一下结束。想只问一句就用旁边的「说一句」
    (点一下开始、再点一下结束并发送,最长 30 秒,按钮上显示已录秒数)。
  · 切句与闭麦都在手机侧做,协议没变:一句还是原来的一个 WAV 上行。
  · **她的声音固定走 A2DP 耳机(0.2.12)**:此前"对话模式"里会改用蓝牙**通话链路**放她的声音,
    而这条链路在部分手机上状态是过期的(SCO 报"已建立",其实声音进了没有音频的链路,
    表现为**一点声音都没有**)。现在固定走媒体通道:连着蓝牙耳机就从耳机出来,
    没耳机就从扬声器出来,两种情况都听得到。
  · **拍照修好(0.2.11 / 0.2.9)**:两个根因都修了 —— 相机拉不起来(FileProvider 里两条
    path 重名,同名互相覆盖,第一个版本起就没成功过);以及拍完正好断线时照片被丢弃
    (新增待发队列,握手完成立刻补发)。
  · **长回答不再没声音(服务端配套)**:服务端对设备通道有一条 **200 字**的长度门槛,
    超了就直接只发文字 —— 表现就是"文字有了、一个字的声音都没有"。现在上限对齐到
    **600 字**,并按标点分段合成(每段 ≤200 字,不撞云端单次请求的长度限制):
    实测同一条 306 字的回答 0 字节 → 75.75 秒 / 3636090 字节,整段念出来。
    另外那次"分段合成"的改动此前**只写在开发目录、没有部署到 AstrBot 真正读的插件目录**,
    这次一并部署并重载(自检脚本 migration_tools/check_live_tts.py 只 import 线上文件)。

v0.2.2
  · 说话按钮改成开关式(点一下开始录、再点一下结束并发送),按钮上实时显示已录秒数;
    30 秒自动结束并发送作为兜底。
  · 语音修复(0.2.1):修掉"按住说话松手后没有任何反应、录音被静默丢掉"的问题 ——
    根因是原生把几个列表字段写成了字符串(Java 的 [A, B, C] 形式),页面按数组用会抛异常,
    而那行渲染恰好排在"把录音排上发送"之前。现在原生输出真数组、页面两种形态都收,
    并且**先把发送排上再去画界面**,界面代码再出错也不会吞掉你说的话。
  · 诊断卡片修复(0.2.1):同一个异常也让"耳机诊断"那一整块渲染不出来,现在正常。

v0.2.0
  · 换手机更好用:新增「家里(Tailscale)」和「同一个 WiFi」两个地址预设按钮;
    令牌留空即走 tailnet 身份认证;第一次进入会显示三步引导卡片。
  · 自动降级:检测到本机不向 App 开放蓝牙麦克风时,自动改用手机麦,并在页面上写清原因。
  · 有线耳麦优先:插上带麦的有线耳机 / USB-C 耳麦时自动把它当作录音输入(不依赖蓝牙 SCO)。
  · 后台保活:连接期间挂前台服务 + 常驻通知(通知上有「停止」),切后台/熄屏不再被系统掐断;
    断线自动重连(指数退避,最长 10 秒),回到前台立刻重连并重新握手;25 秒心跳。
  · SCO 试验:一个不录音的按钮,把蓝牙通话链路按时间线跑一遍(每 200 ms 采样,共 2 秒),
    直接告诉你这台机器能不能建起来。
  · 复制诊断:一键复制完整的设备 / 权限 / 路由 / 档位 / 试验记录,方便远程排障。
  · 设备类型名补全:不再显示 TYPE_25、TYPE_21 这种看不懂的数字,改成带编号和中文
    (例如 TYPE_BLUETOOTH_SCO(7,蓝牙SCO))。
  · 页面新增「当前使用的麦克风」一行;华为/鸿蒙额外显示耗电管理提示。

v0.1.0
  · 第一个能构建、能安装的版本:本地页面 + 按住说话(16 kHz 单声道 WAV)+ 拍照上传 +
    她的语音按到达顺序排队播放。
`;
}

/**
 * 《使用说明-异地手机.txt》:异地测试包(带 Tailscale)里给朋友看的那一份。
 *
 * 与 `installGuide` 的区别:那份是"手机和作者在同一个地方"时用的,两条路线都写;
 * 这一份只服务**人在外地**的收件人 —— 必须装 Tailscale、用自己的账号、接受节点共享,
 * 所以重点是"怎么让自己的手机和作者那台电脑进同一个私有网络",而不是内网地址。
 *
 * @param {object} info 打包信息。
 * @param {string} info.version 轻语手机端版本号。
 * @param {string} info.tailscaleVersion Tailscale Android 版本号。
 * @param {string} info.tailscaleApkFileName 包内 Tailscale APK 文件名。
 * @param {string} info.qingyuApkFileName 包内轻语 APK 文件名。
 * @param {string} info.qingyuSha256 轻语 APK 的 SHA-256。
 * @param {string} info.tailscaleSha256 Tailscale APK 的 SHA-256。
 * @param {string} info.tailnetUrl 连接地址(wss://…:8443/)。
 * @param {string} info.machineName 作者那台电脑在 Tailscale 里的名字。
 * @param {string} info.token 手机中转的令牌;留空表示这份说明**不带令牌**(公开版),
 *   此时那一步会改成"作者单独发给你"。
 * @param {string} info.tailscaleSourceUrl Tailscale 官方发布页(核对来源用)。
 * @returns {string} 纯文本(UTF-8)。
 */
export function remoteKitGuide(info) {
  // 令牌不进公开版本:公开版(Release 资产)里那一步只能说"等作者单独发给你"。
  const tokenStep = info.token
    ? `  3. 令牌填这一串(**只发给你一个人,请不要转发给任何人**):
     ${info.token}`
    : `  3. 令牌:作者会**单独**发给你一串(它等同于密码,请不要转发给任何人),拿到后填进去;`;
  return `轻语 · 异地手机测试包
====================================================
(纯文本,手机和电脑都能直接打开看)

一、需要的东西有三样
  1. ${info.tailscaleApkFileName} —— 组网工具(Tailscale 官方 Android 客户端)
  2. ${info.qingyuApkFileName} —— 「轻语」手机端 App v${info.version}
  3. 本说明

二、为什么还要装 Tailscale
  「轻语」的脑子在作者家里那台电脑上。手机要和它通话,就得先和那台电脑"进同一个私有
  网络"。Tailscale 干的就是这件事:不用公网 IP、不用买服务器、不用改路由器,装上登录就通。
  那台电脑那边已经装好并在跑了,你要做的只有三步:装、登录、接受共享。

三、先装这两个 App(按顺序来)
  1. 点开 ${info.tailscaleApkFileName} → 系统问"是否允许安装未知来源的应用" → 允许 → 安装;
  2. 点开 ${info.qingyuApkFileName} → 同样允许一次 → 安装。
     装好后桌面上应该多出两个图标:Tailscale 和 轻语。

四、登录 Tailscale(用你自己的账号)
  1. 打开 Tailscale,点 Sign in;
  2. 选一个你手上有账号的方式登录(Google / Microsoft / GitHub / Apple 都行)。
     第一次登录它会自动给你建一个免费网络,不收费,也不用理解什么叫 tailnet;
  3. 回到主界面,把连接开关打开,状态显示 Connected 就对了。
  注意:这台手机上的 Tailscale **不需要**跟作者用同一个账号 —— 也**不要**用作者的账号。

五、接受"共享"(关键一步,漏了就一定连不上)
  作者会另外发给你一条**共享邀请链接**(长得像 https://login.tailscale.com/… )。
  1. 用手机浏览器打开那条链接;
  2. 如果它让你登录,就用第四步那个账号;
  3. 页面上会显示一台叫 ${info.machineName} 的电脑,点 Accept(接受)。
  接受之后,打开 Tailscale 的设备列表就能看到这台电脑。你只可能看到这一台:作者网络里
  的其它设备,你既看不到、也连不上。

六、连上她
  1. 打开 轻语;
  2. 地址填(点地址框下面的「家里(Tailscale)」按钮会自动填上):
     ${info.tailnetUrl}
${tokenStep}
  4. 点「连接」,状态变成"已握手 ready"就通了;
  5. 点一下「**开始对话**」就能连着聊:说就行,停顿一下自动发出去,她说话时自动闭麦;
     再点一下结束。只想问一句就用旁边的「说一句」;上方「她听到的」会显示识别出来的文字
     (用来确认收音对不对),她的声音会自动播出来。
  地址和令牌只需要填一次,App 会记住。

七、连不上,按这个顺序查
  1. Tailscale 里显示 Connected 了吗?(没连上就一定说不上话)
  2. 第五步的邀请接受了吗?Tailscale 设备列表里能看到 ${info.machineName} 吗?
  3. 作者那台电脑开着吗?电脑上那个"手机中转"在跑吗?(这条要问作者)
  4. 地址是不是 wss:// 开头、结尾是 :8443/(末尾那个斜杠别丢),令牌有没有多打空格;
  5. Tailscale 里确认一下"使用 Tailscale DNS / MagicDNS"是开着的(新账号默认就开着):
     关掉的话,地址里的那串域名解析不出来,App 会直接报"连接出错";
  6. 还是不行:在 轻语 里点「复制诊断」,把那段文字发回给作者,里面有设备型号、权限、
     蓝牙状态和每次录音用的麦克风,能直接定位问题。

八、已知限制(不是 bug,先看这里)
  1. 部分手机(尤其华为/鸿蒙)不把蓝牙耳机的麦克风开放给第三方 App。这时 App 会自动改用
     手机麦,耳机仍然用来放她的声音,页面上会写明原因。想用"耳机上的麦",插一副**带麦的
     有线耳机(3.5mm)或 USB-C 耳麦**,App 会自动优先用它。
  2. 必须作者那台电脑开着、中转在跑,否则连不上。
  3. 用流量也能连,但会走 Tailscale 的中转服务器,比在同一个 WiFi 里慢一点
     (实测多 0.2~0.5 秒)。
  4. 只有 Android 手机能用,iPhone 装不了 apk。
  5. 这是测试版:你说的话会被送到作者那台电脑上识别、回应,对话记录也留存在那台电脑上,
     作者为了排障可能会查看这些记录。

九、这个包的指纹(想核对有没有传坏可以看)
  ${info.tailscaleApkFileName}
    SHA-256: ${info.tailscaleSha256}
  官方来源:${info.tailscaleSourceUrl}
  ${info.qingyuApkFileName}
    SHA-256: ${info.qingyuSha256}
  核对方法(Windows):certutil -hashfile "文件名" SHA256
`;
}
